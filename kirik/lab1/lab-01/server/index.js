/** Точка запуска процесса сервера. Конфигурация Express живёт отдельно,
 * чтобы тесты могли импортировать app и слушать свободный порт вместо 3100.
 */
import { app } from './app.js';

// Переменная окружения — строка. ?? использует 3100 только при null/undefined;
// пустая или ошибочная строка не скрывается и отклоняется проверкой ниже.
const port = Number(process.env.PORT ?? 3100);
if (!Number.isInteger(port) || port < 1 || port > 65535) {
  throw new Error('PORT должен быть целым числом от 1 до 65535');
}

// 0.0.0.0 означает все IPv4-интерфейсы, что позволяет подключить телефон по IP ПК.
// Это адрес прослушивания, а не адрес, который надо вводить на телефоне.
const server = app.listen(port, '0.0.0.0', () => {
  console.log(`Сервер запущен: http://localhost:${port}`);
});

// Например, занятый порт вызывает событие error. Ненулевой exitCode сообщает
// оболочке о неудаче; процесс завершится, когда не останется активной работы.
server.on('error', (error) => {
  console.error(`Не удалось запустить сервер: ${error.message}`);
  process.exitCode = 1;
});
